# ==========================================
# TYPE CASTING IN PYTHON
# ==========================================

# 1. String to Integer
num = "100"
print("String:", num)
print("Converted to Integer:", int(num))

print("----------------------------")

# 2. Integer to String
age = 21
print("Integer:", age)
print("Converted to String:", str(age))

print("----------------------------")

# 3. Float to Integer
price = 99.99
print("Float:", price)
print("Converted to Integer:", int(price))

print("----------------------------")

# 4. Integer to Float
marks = 85
print("Integer:", marks)
print("Converted to Float:", float(marks))

print("----------------------------")

# 5. String to Float
weight = "63.5"
print("String:", weight)
print("Converted to Float:", float(weight))

print("----------------------------")

# 6. Float to String
cgpa = 8.38
print("Float:", cgpa)
print("Converted to String:", str(cgpa))