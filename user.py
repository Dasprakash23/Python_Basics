# Taking string input
name = input("Enter your name: ")

# Taking integer input
age = int(input("Enter your age: "))

# Taking float input
height = float(input("Enter your height in meters: "))

# Displaying the values
print("\n----- User Details -----")
print("Name :", name)
print("Age :", age)
print("Height :", height, "meters")