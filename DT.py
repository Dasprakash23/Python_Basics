# ==========================
# 1. Integer (int)
# ==========================
age = 21
print("Integer Value:", age)
print("Data Type:", type(age))
print()

# ==========================
# 2. Float (float)
# ==========================
cgpa = 8.4
print("Float Value:", cgpa)
print("Data Type:", type(cgpa))
print()

# ==========================
# 3. String (str)
# ==========================
name = "Dasprakash"
print("String Value:", name)
print("Data Type:", type(name))
print()

# ==========================
# 4. Boolean (bool)
# ==========================
is_student = True
print("Boolean Value:", is_student)
print("Data Type:", type(is_student))
print()

# ==========================
# 5. List (list)
# ==========================
skills = ["Python", "Java", "C++", "HTML"]
print("List Value:", skills)
print("Data Type:", type(skills))
print()

# ==========================
# 6. Tuple (tuple)
# ==========================
marks = (85, 90, 95)
print("Tuple Value:", marks)
print("Data Type:", type(marks))
print()

# ==========================
# 7. Set (set)
# ==========================
subjects = {"Python", "Java", "DBMS"}
print("Set Value:", subjects)
print("Data Type:", type(subjects))
print()

# ==========================
# 8. Dictionary (dict)
# ==========================
student = {
    "Name": "Dasprakash",
    "Age": 21,
    "CGPA": 8.4
}

print("Dictionary Value:", student)
print("Data Type:", type(student))
print()

# ==========================
# 9. None Type (NoneType)
# ==========================
result = None
print("None Value:", result)
print("Data Type:", type(result))
print()

