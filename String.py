# ------------------------------------
# Python Strings Example
# ------------------------------------

text = "Hello Python"

print("Original String :", text)

# Length
print("Length :", len(text))

# Uppercase
print("Uppercase :", text.upper())

# Lowercase
print("Lowercase :", text.lower())

# Replace
print("Replace :", text.replace("Python", "World"))

# First character
print("First Character :", text[0])

# Last character
print("Last Character :", text[-1])

# Slicing
print("First Five Characters :", text[:5])

# Concatenation
name = "Leo"
print("Welcome " + name)

# Repetition
print(name * 3)